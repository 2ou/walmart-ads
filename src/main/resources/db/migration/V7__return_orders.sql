CREATE TABLE wm_ads_return_order (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    import_file_id BIGINT NOT NULL,
    source_row_number INT NOT NULL,
    business_key CHAR(64) NOT NULL,
    report_month DATE NOT NULL,
    request_at DATETIME(6) NOT NULL,
    request_date DATE NOT NULL,
    customer_order_no VARCHAR(80) NOT NULL,
    po_no VARCHAR(80) NULL,
    po_line_no VARCHAR(40) NULL,
    rma_no VARCHAR(100) NOT NULL,
    return_order_line_no VARCHAR(40) NULL,
    quantity DECIMAL(18,4) NOT NULL DEFAULT 0,
    return_reason VARCHAR(300) NULL,
    item_id VARCHAR(80) NOT NULL,
    sku VARCHAR(180) NULL,
    parent_sku VARCHAR(80) NULL,
    condition_name VARCHAR(80) NULL,
    current_status VARCHAR(100) NULL,
    current_status_time DATETIME(6) NULL,
    keep_it BOOLEAN NOT NULL DEFAULT FALSE,
    item_name TEXT NULL,
    carrier VARCHAR(80) NULL,
    tracking_number VARCHAR(200) NULL,
    channel VARCHAR(120) NULL,
    customer_name VARCHAR(300) NULL,
    customer_email VARCHAR(500) NULL,
    customer_comments TEXT NULL,
    order_amount DECIMAL(18,6) NOT NULL DEFAULT 0,
    return_shipping_fee DECIMAL(18,6) NOT NULL DEFAULT 0,
    restocking_fee DECIMAL(18,6) NOT NULL DEFAULT 0,
    total_refund_amount DECIMAL(18,6) NOT NULL DEFAULT 0,
    seller_order_no VARCHAR(100) NULL,
    refund_mode VARCHAR(100) NULL,
    refund_covered_by VARCHAR(120) NULL,
    tracking_status VARCHAR(100) NULL,
    refund_status VARCHAR(100) NULL,
    replacement BOOLEAN NOT NULL DEFAULT FALSE,
    platform_type VARCHAR(80) NULL,
    return_ship_from VARCHAR(120) NULL,
    return_ship_to VARCHAR(120) NULL,
    raw_payload JSON NOT NULL,
    created_at DATETIME(6) NOT NULL,
    CONSTRAINT fk_return_order_import_file
        FOREIGN KEY (import_file_id) REFERENCES wm_ads_import_file(id),
    CONSTRAINT uk_return_order_file_row UNIQUE (import_file_id, source_row_number),
    INDEX idx_return_business_key (business_key),
    INDEX idx_return_request_date (request_date),
    INDEX idx_return_report_month (report_month),
    INDEX idx_return_item_date (item_id, request_date),
    INDEX idx_return_sku_date (sku, request_date),
    INDEX idx_return_parent_date (parent_sku, request_date),
    INDEX idx_return_customer_order (customer_order_no),
    INDEX idx_return_rma (rma_no)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
