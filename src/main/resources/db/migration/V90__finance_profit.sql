-- PNK (workspace-scoped) monthly store & style financial profit tables.
-- USD P&L columns: sales revenue & reimbursements are positive, refunds & platform fees are negative.
-- CNY cost columns: expenses are normalized to positive, return cost reversals / rebates are negative.
-- Universal accounting identity: gross_profit_cny = net_settlement_cny - purchase_cost_cny - first_leg_freight_cny - offsite_ad_cny - offsite_fee_cny.

CREATE TABLE wm_ads_finance_import_batch (
    id BIGINT NOT NULL AUTO_INCREMENT,
    workspace_id BIGINT NOT NULL,
    account_code VARCHAR(32) NOT NULL,
    file_name VARCHAR(255) NOT NULL,
    file_sha256 CHAR(64) NOT NULL,
    template_era VARCHAR(24) NOT NULL,
    file_report_month CHAR(7) NOT NULL,
    store_months_imported INT NOT NULL DEFAULT 0,
    style_months_imported INT NOT NULL DEFAULT 0,
    style_rows_imported INT NOT NULL DEFAULT 0,
    imported_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    UNIQUE KEY uq_fin_batch_ws_sha (workspace_id, file_sha256),
    KEY idx_fin_batch_ws_month (workspace_id, file_report_month, imported_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE wm_ads_finance_store_monthly (
    id BIGINT NOT NULL AUTO_INCREMENT,
    workspace_id BIGINT NOT NULL,
    account_code VARCHAR(32) NOT NULL,
    company_name VARCHAR(64) NULL,
    report_year INT NOT NULL,
    report_month CHAR(7) NOT NULL,
    settlement_period VARCHAR(40) NULL,
    exchange_rate DECIMAL(12,6) NOT NULL DEFAULT 0,
    sales_revenue_usd DECIMAL(18,4) NOT NULL DEFAULT 0,
    refund_usd DECIMAL(18,4) NOT NULL DEFAULT 0,
    commission_usd DECIMAL(18,4) NOT NULL DEFAULT 0,
    wfs_fee_usd DECIMAL(18,4) NOT NULL DEFAULT 0,
    ad_spend_usd DECIMAL(18,4) NOT NULL DEFAULT 0,
    storage_fee_usd DECIMAL(18,4) NOT NULL DEFAULT 0,
    inventory_reimbursement_usd DECIMAL(18,4) NOT NULL DEFAULT 0,
    inventory_disposal_usd DECIMAL(18,4) NOT NULL DEFAULT 0,
    promo_discount_usd DECIMAL(18,4) NOT NULL DEFAULT 0,
    other_platform_fee_usd DECIMAL(18,4) NOT NULL DEFAULT 0,
    net_settlement_usd DECIMAL(18,4) NOT NULL DEFAULT 0,
    settlement_ratio DECIMAL(12,6) NOT NULL DEFAULT 0,
    net_settlement_cny DECIMAL(18,4) NOT NULL DEFAULT 0,
    purchase_cost_cny DECIMAL(18,4) NOT NULL DEFAULT 0,
    first_leg_freight_cny DECIMAL(18,4) NOT NULL DEFAULT 0,
    offsite_ad_cny DECIMAL(18,4) NOT NULL DEFAULT 0,
    offsite_fee_cny DECIMAL(18,4) NOT NULL DEFAULT 0,
    gross_profit_cny DECIMAL(18,4) NOT NULL DEFAULT 0,
    profit_margin DECIMAL(12,6) NOT NULL DEFAULT 0,
    sales_qty INT NOT NULL DEFAULT 0,
    refund_qty INT NOT NULL DEFAULT 0,
    return_qty INT NOT NULL DEFAULT 0,
    return_sellable_qty INT NULL,
    has_style_detail BOOLEAN NOT NULL DEFAULT FALSE,
    style_reconcile_diff_cny DECIMAL(18,4) NULL,
    source_file_name VARCHAR(255) NOT NULL,
    source_batch_id BIGINT NULL,
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    UNIQUE KEY uq_fin_store_ws_acc_month (workspace_id, account_code, report_month),
    KEY idx_fin_store_ws_month (workspace_id, report_month)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

