CREATE TABLE wm_ads_item_report_record (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    import_file_id BIGINT NOT NULL,
    source_updated_at DATETIME(6) NOT NULL,
    current_version BOOLEAN NOT NULL DEFAULT TRUE,
    sku VARCHAR(180) NOT NULL,
    parent_sku VARCHAR(80) NULL,
    item_id VARCHAR(40) NULL,
    upc VARCHAR(40) NULL,
    wpid VARCHAR(40) NULL,
    gtin VARCHAR(40) NULL,
    product_name TEXT NULL,
    brand VARCHAR(120) NULL,
    product_category VARCHAR(255) NULL,
    lifecycle_status VARCHAR(40) NULL,
    fulfillment_type VARCHAR(40) NULL,
    price DECIMAL(18,6) NOT NULL DEFAULT 0,
    currency VARCHAR(10) NULL,
    price_type VARCHAR(40) NULL,
    shipping_weight_lb DECIMAL(18,6) NOT NULL DEFAULT 0,
    shipping_weight_unit VARCHAR(10) NULL,
    shipping_weight_kg DECIMAL(18,6) NOT NULL DEFAULT 0,
    billing_weight_lb DECIMAL(18,6) NOT NULL DEFAULT 0,
    base_fee DECIMAL(18,6) NOT NULL DEFAULT 0,
    apparel_surcharge DECIMAL(18,6) NOT NULL DEFAULT 0,
    low_price_surcharge DECIMAL(18,6) NOT NULL DEFAULT 0,
    delivery_fee DECIMAL(18,6) NOT NULL DEFAULT 0,
    raw_payload JSON NOT NULL,
    created_at DATETIME(6) NOT NULL,
    CONSTRAINT fk_item_report_import_file FOREIGN KEY (import_file_id) REFERENCES wm_ads_import_file(id),
    INDEX idx_item_report_sku_current (sku, current_version),
    INDEX idx_item_report_parent (parent_sku),
    INDEX idx_item_report_upc (upc)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
