-- 穿针引线供应链：补齐生产订单主档与物流信息登记两个只读快照。
CREATE TABLE wm_ads_supply_order (
    id BIGINT NOT NULL AUTO_INCREMENT,
    workspace_id BIGINT NOT NULL DEFAULT 1,
    source_key CHAR(64) NOT NULL,
    source_id VARCHAR(80) NULL,
    order_no VARCHAR(120) NOT NULL,
    order_status VARCHAR(80) NULL,
    style_no VARCHAR(120) NULL,
    order_type VARCHAR(120) NULL,
    factory_name VARCHAR(160) NULL,
    warehouse_name VARCHAR(160) NULL,
    store_name VARCHAR(120) NULL,
    order_qty DECIMAL(18, 4) NOT NULL DEFAULT 0,
    cutting_qty DECIMAL(18, 4) NOT NULL DEFAULT 0,
    ship_qty DECIMAL(18, 4) NOT NULL DEFAULT 0,
    warehouse_receive_qty DECIMAL(18, 4) NOT NULL DEFAULT 0,
    qc_pass_qty DECIMAL(18, 4) NOT NULL DEFAULT 0,
    unfinished_qty DECIMAL(18, 4) NOT NULL DEFAULT 0,
    placed_at DATETIME NULL,
    assigned_at DATETIME NULL,
    factory_return_date VARCHAR(60) NULL,
    completed_at DATETIME NULL,
    active TINYINT(1) NOT NULL DEFAULT 1,
    snapshot_at DATETIME(6) NOT NULL,
    raw_payload JSON NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_supply_order_source_workspace (workspace_id, source_key),
    INDEX idx_supply_order_workspace_active (workspace_id, active, order_no),
    INDEX idx_supply_order_style (workspace_id, style_no),
    INDEX idx_supply_order_snapshot (workspace_id, snapshot_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='供应链生产订单主档当前快照';

CREATE TABLE wm_ads_supply_logistics_register (
    id BIGINT NOT NULL AUTO_INCREMENT,
    workspace_id BIGINT NOT NULL DEFAULT 1,
    source_key CHAR(64) NOT NULL,
    source_id VARCHAR(80) NULL,
    fba_number VARCHAR(160) NULL,
    account_number VARCHAR(160) NULL,
    delivery_warehouse_name VARCHAR(160) NULL,
    freight_forwarding_name VARCHAR(160) NULL,
    destination VARCHAR(120) NULL,
    channel_name VARCHAR(240) NULL,
    receiving_warehouse VARCHAR(160) NULL,
    amazon_warehouse VARCHAR(160) NULL,
    batch_number VARCHAR(120) NULL,
    take_goods_no VARCHAR(160) NULL,
    logistics_no VARCHAR(160) NULL,
    cases_qty DECIMAL(18, 4) NOT NULL DEFAULT 0,
    item_qty DECIMAL(18, 4) NOT NULL DEFAULT 0,
    shipping_weight DECIMAL(18, 4) NOT NULL DEFAULT 0,
    charged_weight DECIMAL(18, 4) NOT NULL DEFAULT 0,
    final_offer DECIMAL(18, 4) NOT NULL DEFAULT 0,
    logistics_amount DECIMAL(18, 4) NOT NULL DEFAULT 0,
    ship_date DATE NULL,
    assigned_at DATETIME NULL,
    transportation_date DATE NULL,
    signing_date DATE NULL,
    shipment_status VARCHAR(100) NULL,
    flow_status VARCHAR(60) NULL,
    request_status VARCHAR(60) NULL,
    exception_note VARCHAR(1000) NULL,
    active TINYINT(1) NOT NULL DEFAULT 1,
    snapshot_at DATETIME(6) NOT NULL,
    raw_payload JSON NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_supply_logistics_source_workspace (workspace_id, source_key),
    INDEX idx_supply_logistics_workspace_active (workspace_id, active, fba_number),
    INDEX idx_supply_logistics_transport (workspace_id, transportation_date),
    INDEX idx_supply_logistics_snapshot (workspace_id, snapshot_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='供应链物流信息登记当前快照';

