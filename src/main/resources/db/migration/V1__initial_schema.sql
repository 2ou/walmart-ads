CREATE TABLE wm_ads_import_batch (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    started_at DATETIME(6) NOT NULL,
    completed_at DATETIME(6) NULL,
    status VARCHAR(20) NOT NULL,
    source_root VARCHAR(1000) NOT NULL,
    archive_directory VARCHAR(1000) NULL,
    discovered_file_count INT NOT NULL DEFAULT 0,
    imported_file_count INT NOT NULL DEFAULT 0,
    skipped_file_count INT NOT NULL DEFAULT 0,
    failed_file_count INT NOT NULL DEFAULT 0,
    message TEXT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE wm_ads_import_file (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    batch_id BIGINT NOT NULL,
    file_type VARCHAR(30) NOT NULL,
    file_name VARCHAR(500) NOT NULL,
    original_path VARCHAR(1200) NOT NULL,
    archive_path VARCHAR(1200) NULL,
    sha256 CHAR(64) NOT NULL,
    size_bytes BIGINT NOT NULL,
    source_modified_at DATETIME(6) NOT NULL,
    report_date DATE NULL,
    snapshot_at DATETIME(6) NULL,
    status VARCHAR(20) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    source_row_count INT NOT NULL DEFAULT 0,
    imported_row_count INT NOT NULL DEFAULT 0,
    error_message TEXT NULL,
    created_at DATETIME(6) NOT NULL,
    CONSTRAINT fk_import_file_batch FOREIGN KEY (batch_id) REFERENCES wm_ads_import_batch(id),
    CONSTRAINT uk_import_file_hash_type UNIQUE (sha256, file_type),
    INDEX idx_import_file_report (file_type, report_date, active),
    INDEX idx_import_file_snapshot (file_type, snapshot_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

