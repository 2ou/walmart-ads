package com.ai.walmartads.inventory.application;

import com.ai.walmartads.workspace.WorkspaceContext;
import com.ai.walmartads.workspace.WorkspacePrincipal;
import com.fasterxml.jackson.databind.ObjectMapper;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

import java.math.BigDecimal;
import java.time.LocalDateTime;
import java.util.UUID;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

class LingxingDomesticInventoryServiceTest {

    private JdbcTemplate jdbc;
    private ObjectMapper objectMapper;
    private LingxingDomesticInventoryService service;

    @BeforeEach
    void setUp() {
        String database = "lx_domestic_" + UUID.randomUUID().toString().replace("-", "");
        jdbc = new JdbcTemplate(new DriverManagerDataSource(
                "jdbc:h2:mem:" + database + ";MODE=MySQL;DATABASE_TO_LOWER=TRUE;DB_CLOSE_DELAY=-1", "sa", ""));
        jdbc.execute("""
                create table wm_ads_lx_domestic_inventory (
                    id bigint generated by default as identity primary key,
                    workspace_id bigint not null,
                    sku varchar(180) not null,
                    available_units decimal(18,4) not null,
                    warehouse_name varchar(255), store_name varchar(255), source_url varchar(500) not null,
                    raw_payload clob not null, synced_at timestamp not null,
                    created_at timestamp not null, updated_at timestamp not null,
                    unique(workspace_id, sku)
                )
                """);
        jdbc.execute("""
                create table wm_ads_lx_domestic_inventory_sync_log (
                    id bigint generated by default as identity primary key,
                    workspace_id bigint not null, started_at timestamp not null, finished_at timestamp,
                    status varchar(20) not null, source_row_count int not null,
                    imported_sku_count int not null, skipped_row_count int not null,
                    available_units decimal(18,4) not null, source_url varchar(500), message varchar(1000)
                )
                """);
        jdbc.execute("""
                create table wm_ads_import_file (
                    id bigint primary key, workspace_id bigint not null, active boolean not null
                )
                """);
        jdbc.execute("""
                create table wm_ads_domestic_inventory_snapshot (
                    id bigint generated by default as identity primary key,
                    workspace_id bigint not null, import_file_id bigint not null,
                    snapshot_at timestamp not null, sku varchar(180) not null,
                    available_units decimal(18,4) not null
                )
                """);
        objectMapper = new ObjectMapper();
        service = new LingxingDomesticInventoryService(jdbc, objectMapper);
        WorkspaceContext.set(new WorkspacePrincipal(
                7L, "PINKSIR", "ACTIVE", "store-7", "PINKSIR", "PNK", true, 1L));
    }

    @AfterEach
    void tearDown() {
        WorkspaceContext.clear();
    }

    @Test
    void replacesCurrentSnapshotAndAggregatesDuplicateSkuRows() throws Exception {
        var response = objectMapper.readTree("""
                {"code":1,"data":{"list":[
                  {"sku":"PNK-A","available_quantity":"2","warehouse_name":"国内仓一"},
                  {"sku":"PNK-A","available_quantity":3,"warehouse_name":"国内仓二"},
                  {"seller_sku":"PNK-B","availableStock":"1","store_name":"PINKSIR"},
                  {"sku":"OTHER-A","available_quantity":99}
                ],"total":4}}
                """);

        var result = service.replaceFromConnector(
                "https://czyx.lingxing.com/api/storage/lists?page=1", response, LocalDateTime.now());

        assertThat(result.sourceRows()).isEqualTo(4);
        assertThat(result.importedSkus()).isEqualTo(2);
        assertThat(result.skippedRows()).isEqualTo(1);
        assertThat(result.availableUnits()).isEqualByComparingTo("6");
        assertThat(jdbc.queryForObject(
                "select available_units from wm_ads_lx_domestic_inventory where workspace_id=7 and sku='PNK-A'",
                BigDecimal.class)).isEqualByComparingTo("5");

        var status = service.status();
        assertThat(status.activeSource()).isEqualTo("PROJECT_CONNECTOR");
        assertThat(status.skuCount()).isEqualTo(2);
        assertThat(status.availableUnits()).isEqualByComparingTo("6");
    }

    @Test
    void invalidOrWrongStoreResponseCannotEraseLastGoodSnapshot() throws Exception {
        jdbc.update("""
                insert into wm_ads_lx_domestic_inventory(
                    workspace_id, sku, available_units, source_url, raw_payload,
                    synced_at, created_at, updated_at
                ) values (7, 'PNK-KEEP', 8, ?, '{}', now(), now(), now())
                """, "https://czyx.lingxing.com/api/storage/lists");
        var response = objectMapper.readTree("""
                {"data":{"rows":[{"sku":"OTHER-A","available_num":3}]}}
                """);

        assertThatThrownBy(() -> service.replaceFromConnector(
                "https://czyx.lingxing.com/api/storage/lists", response, LocalDateTime.now()))
                .isInstanceOf(IllegalArgumentException.class)
                .hasMessageContaining("已保留原库存");
        assertThat(jdbc.queryForObject(
                "select count(*) from wm_ads_lx_domestic_inventory where workspace_id=7", Integer.class))
                .isEqualTo(1);
    }

    @Test
    void importsCurrentLingxingRowsBySummingWarehouseBins() throws Exception {
        var response = objectMapper.readTree("""
                {"code":1,"data":{"list":[
                  {"sku":"PNK-BIN","wh_name":"美国仓-沃尔玛","bin_arr":[
                    {"whb_name":"默认库位","product_total":4},
                    {"whb_name":"退货库位","product_total":"2"}
                  ]},
                  {"sku":"OTHER-BIN","bin_arr":[{"product_total":99}]}
                ],"total":2}}
                """);

        var result = service.replaceFromConnector(
                "https://czyx.lingxing.com/api/storage/lists", response, LocalDateTime.now());

        assertThat(result.importedSkus()).isEqualTo(1);
        assertThat(result.availableUnits()).isEqualByComparingTo("6");
        assertThat(jdbc.queryForObject(
                "select available_units from wm_ads_lx_domestic_inventory where workspace_id=7 and sku='PNK-BIN'",
                BigDecimal.class)).isEqualByComparingTo("6");
        assertThat(jdbc.queryForObject(
                "select warehouse_name from wm_ads_lx_domestic_inventory where workspace_id=7 and sku='PNK-BIN'",
                String.class)).isEqualTo("美国仓-沃尔玛");
    }

    @Test
    void rejectsAnyEndpointOutsideTheDocumentedReadOnlyList() throws Exception {
        var response = objectMapper.readTree("""
                {"data":{"list":[{"sku":"PNK-A","available_num":1}]}}
                """);

        assertThatThrownBy(() -> service.replaceFromConnector(
                "https://czyx.lingxing.com/api/storage/update", response, LocalDateTime.now()))
                .isInstanceOf(IllegalArgumentException.class)
                .hasMessageContaining("只接受");
    }

    @Test
    void incompleteSnapshotCannotReplaceHistoricalFullSnapshot() throws Exception {
        jdbc.update("""
                insert into wm_ads_lx_domestic_inventory(
                    workspace_id, sku, available_units, source_url, raw_payload,
                    synced_at, created_at, updated_at
                ) values (7, 'PNK-KEEP', 8, ?, '{}', now(), now(), now())
                """, "https://czyx.lingxing.com/api/storage/lists");
        jdbc.update("""
                insert into wm_ads_lx_domestic_inventory_sync_log(
                    workspace_id,started_at,finished_at,status,source_row_count,
                    imported_sku_count,skipped_row_count,available_units,source_url,message
                ) values (7,now(),now(),'SUCCESS',1130,970,23,139,?, 'historical full snapshot')
                """, "https://czyx.lingxing.com/api/storage/lists");
        var rows = objectMapper.createArrayNode();
        for (int index = 0; index < 468; index++) {
            rows.addObject().put("sku", "PNK-" + index).put("available_num", 0);
        }
        var response = objectMapper.createObjectNode();
        response.put("code", 1).putObject("data").put("total", 468).set("list", rows);

        assertThatThrownBy(() -> service.replaceFromConnector(
                "https://czyx.lingxing.com/api/storage/lists", response, LocalDateTime.now()))
                .isInstanceOf(IllegalArgumentException.class)
                .hasMessageContaining("疑似不完整")
                .hasMessageContaining("已保留原库存");
        assertThat(jdbc.queryForObject(
                "select count(*) from wm_ads_lx_domestic_inventory where workspace_id=7", Integer.class))
                .isEqualTo(1);
    }

    @Test
    void declaredTotalMustBeFullyPresent() throws Exception {
        var response = objectMapper.readTree("""
                {"code":1,"data":{"list":[{"sku":"PNK-A","available_num":1}],"total":2}}
                """);

        assertThatThrownBy(() -> service.replaceFromConnector(
                "https://czyx.lingxing.com/api/storage/lists", response, LocalDateTime.now()))
                .isInstanceOf(IllegalArgumentException.class)
                .hasMessageContaining("1/2")
                .hasMessageContaining("已保留原库存");
    }
}
