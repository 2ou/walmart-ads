-- 穿针引线供应链：生产中订单 + 生产发货单的原子快照。
CREATE TABLE wm_ads_supply_production_order (
    id BIGINT NOT NULL AUTO_INCREMENT,
    source_key CHAR(64) NOT NULL,
    source_id VARCHAR(80) NULL,
    order_no VARCHAR(120) NULL,
    style_no VARCHAR(120) NULL,
    sku VARCHAR(180) NOT NULL,
    order_date DATE NULL,
    model VARCHAR(80) NULL,
    open_qty DECIMAL(18, 4) NOT NULL DEFAULT 0,
    cutting_qty DECIMAL(18, 4) NOT NULL DEFAULT 0,
    production_qty DECIMAL(18, 4) NOT NULL DEFAULT 0,
    ship_qty DECIMAL(18, 4) NOT NULL DEFAULT 0,
    warehouse_receive_qty DECIMAL(18, 4) NOT NULL DEFAULT 0,
    qc_pass_qty DECIMAL(18, 4) NOT NULL DEFAULT 0,
    rework_qty DECIMAL(18, 4) NOT NULL DEFAULT 0,
    unfinished_qty DECIMAL(18, 4) NOT NULL DEFAULT 0,
    factory_return_date VARCHAR(60) NULL,
    store_name VARCHAR(120) NULL,
    order_type VARCHAR(120) NULL,
    factory_name VARCHAR(160) NULL,
    warehouse_name VARCHAR(160) NULL,
    active TINYINT(1) NOT NULL DEFAULT 1,
    snapshot_at DATETIME(6) NOT NULL,
    raw_payload JSON NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_supply_production_source (source_key),
    INDEX idx_supply_production_active_sku (active, sku),
    INDEX idx_supply_production_order (order_no),
    INDEX idx_supply_production_snapshot (snapshot_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='供应链生产中订单当前快照';

CREATE TABLE wm_ads_supply_delivery_detail (
    id BIGINT NOT NULL AUTO_INCREMENT,
    source_key CHAR(64) NOT NULL,
    source_id VARCHAR(80) NULL,
    delivery_no VARCHAR(120) NOT NULL,
    order_no VARCHAR(120) NULL,
    style_no VARCHAR(120) NULL,
    sku VARCHAR(180) NOT NULL,
    cutting_no VARCHAR(120) NULL,
    model VARCHAR(80) NULL,
    order_qty DECIMAL(18, 4) NOT NULL DEFAULT 0,
    ship_qty DECIMAL(18, 4) NOT NULL DEFAULT 0,
    warehouse_receive_qty DECIMAL(18, 4) NOT NULL DEFAULT 0,
    qc_receive_qty DECIMAL(18, 4) NOT NULL DEFAULT 0,
    qc_pass_qty DECIMAL(18, 4) NOT NULL DEFAULT 0,
    rework_qty DECIMAL(18, 4) NOT NULL DEFAULT 0,
    delivery_status VARCHAR(80) NULL,
    plan_flag VARCHAR(40) NULL,
    logistics_complete TINYINT(1) NULL,
    assigned_at DATETIME NULL,
    source_created_at DATETIME NULL,
    factory_name VARCHAR(160) NULL,
    warehouse_name VARCHAR(160) NULL,
    active TINYINT(1) NOT NULL DEFAULT 1,
    snapshot_at DATETIME(6) NOT NULL,
    raw_payload JSON NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_supply_delivery_source (source_key),
    INDEX idx_supply_delivery_active_sku (active, sku),
    INDEX idx_supply_delivery_no (delivery_no),
    INDEX idx_supply_delivery_order_sku (order_no, sku),
    INDEX idx_supply_delivery_snapshot (snapshot_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='供应链生产发货单SKU明细当前快照';

CREATE TABLE wm_ads_supply_chain_sync_log (
    id BIGINT NOT NULL AUTO_INCREMENT,
    started_at DATETIME(6) NOT NULL,
    finished_at DATETIME(6) NULL,
    status VARCHAR(20) NOT NULL COMMENT 'RUNNING / SUCCESS / FAILED / SKIPPED',
    triggered_by VARCHAR(20) NOT NULL COMMENT 'CRON / MANUAL',
    production_count INT NOT NULL DEFAULT 0,
    delivery_sheet_count INT NOT NULL DEFAULT 0,
    delivery_detail_count INT NOT NULL DEFAULT 0,
    duration_ms BIGINT NOT NULL DEFAULT 0,
    error_message TEXT NULL,
    PRIMARY KEY (id),
    INDEX idx_supply_sync_started (started_at),
    INDEX idx_supply_sync_status (status, finished_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='供应链双接口同步运行记录';
