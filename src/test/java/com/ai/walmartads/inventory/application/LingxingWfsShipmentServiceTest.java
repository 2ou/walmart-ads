package com.ai.walmartads.inventory.application;

import com.ai.walmartads.workspace.WorkspaceContext;
import com.ai.walmartads.workspace.WorkspacePrincipal;
import com.fasterxml.jackson.databind.ObjectMapper;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

import java.math.BigDecimal;
import java.time.LocalDateTime;
import java.util.UUID;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;
import static org.mockito.Mockito.mock;

class LingxingWfsShipmentServiceTest {

    private JdbcTemplate jdbc;
    private ObjectMapper objectMapper;
    private LingxingWfsShipmentService service;

    @BeforeEach
    void setUp() {
        String database = "lx_wfs_" + UUID.randomUUID().toString().replace("-", "");
        jdbc = new JdbcTemplate(new DriverManagerDataSource(
                "jdbc:h2:mem:" + database + ";MODE=MySQL;DATABASE_TO_LOWER=TRUE;DB_CLOSE_DELAY=-1", "sa", ""));
        jdbc.execute("""
                create table wm_ads_shipment_record (
                    id bigint generated by default as identity primary key,
                    workspace_id bigint not null,
                    source_type varchar(32) not null,
                    source_url varchar(500), synced_at timestamp, import_file_id bigint,
                    current_version boolean not null,
                    shipment_no varchar(120) not null, local_status varchar(80) not null,
                    shipment_created_at timestamp, sku varchar(180) not null, parent_sku varchar(80),
                    receipt_difference decimal(18,4) not null, raw_payload clob not null,
                    created_at timestamp not null
                )
                """);
        jdbc.execute("""
                create table wm_ads_lx_wfs_shipment_sync_log (
                    id bigint generated by default as identity primary key,
                    workspace_id bigint not null, started_at timestamp not null, finished_at timestamp,
                    status varchar(20) not null, source_shipment_count int not null,
                    imported_shipment_count int not null, imported_row_count int not null,
                    skipped_row_count int not null, transit_units decimal(18,4) not null,
                    source_url varchar(500), message varchar(1000)
                )
                """);
        objectMapper = new ObjectMapper();
        service = new LingxingWfsShipmentService(jdbc, objectMapper, mock(ReplenishmentPlanCache.class));
        WorkspaceContext.set(new WorkspacePrincipal(
                7L, "PINKSIR", "ACTIVE", "store-7", "PINKSIR", "PNK", true, 1L));
    }

    @AfterEach
    void tearDown() {
        WorkspaceContext.clear();
    }

    @Test
    void replacesCurrentFileSnapshotWithValidatedLingxingRows() throws Exception {
        jdbc.update("""
                insert into wm_ads_shipment_record(
                    workspace_id, source_type, synced_at, import_file_id, current_version,
                    shipment_no, local_status, sku, receipt_difference, raw_payload, created_at
                ) values (7, 'FILE_UPLOAD', now(), 10, true, 'OLD', '已申报', 'PNK-OLD', 9, '{}', now())
                """);
        var response = objectMapper.readTree("""
                {"code":1,"data":{"total":2,"list":[
                  {"cargoCode":"3333749WFB","cargoStatusName":"已申报",
                   "cargoCreateDate":"2026-10-17 10:13","updateDate":"2026-10-17 14:40",
                   "cargoListGoodsDetailResponses":[
                     {"sku":"PNK-A-1X-WFS","declareNum":33,"shipmentsNum":33,"receivedNum":0,
                      "damegedQty":0,"diffOfDeclareAndSign":33},
                     {"sku":"PNK-A-2X-WFS","declareNum":20,"shipmentsNum":20,"receivedNum":0,
                      "damegedQty":0,"diffOfDeclareAndSign":20},
                     {"sku":"OTHER-A","declareNum":99,"diffOfDeclareAndSign":99}
                   ]},
                  {"cargoCode":"3225813WFB","cargoStatusName":"已完成",
                   "cargoCreateDate":"2026-10-15 03:33","updateDate":"2026-10-17 02:55",
                   "cargoListGoodsDetailResponses":[
                     {"sku":"PNK-B-1X-WFS","declareNum":10,"shipmentsNum":0,"receivedNum":10,
                      "damegedQty":1,"diffOfDeclareAndSign":0}
                   ]}
                ]}}
                """);

        var result = service.replaceFromConnector(
                "https://gw.lingxingerp.com/mp-platform-warehouse-api/api/cargo/list",
                response, LocalDateTime.now());

        assertThat(result.sourceShipments()).isEqualTo(2);
        assertThat(result.importedShipments()).isEqualTo(2);
        assertThat(result.importedRows()).isEqualTo(3);
        assertThat(result.transitUnits()).isEqualByComparingTo("53");
        assertThat(jdbc.queryForObject(
                "select current_version from wm_ads_shipment_record where shipment_no='OLD'", Boolean.class)).isFalse();
        assertThat(jdbc.queryForObject(
                "select count(*) from wm_ads_shipment_record where source_type='PROJECT_CONNECTOR'", Integer.class))
                .isEqualTo(3);
        assertThat(jdbc.queryForObject(
                "select raw_payload from wm_ads_shipment_record where sku='PNK-B-1X-WFS'", String.class))
                .contains("签收量(损坏)", "10(1)", "更新时间");

        var status = service.status();
        assertThat(status.activeSource()).isEqualTo("PROJECT_CONNECTOR");
        assertThat(status.shipmentCount()).isEqualTo(2);
        assertThat(status.itemCount()).isEqualTo(3);
        assertThat(status.transitUnits()).isEqualByComparingTo(BigDecimal.valueOf(53));
    }

    @Test
    void incompleteResponseCannotEraseLastGoodSnapshot() throws Exception {
        jdbc.update("""
                insert into wm_ads_shipment_record(
                    workspace_id, source_type, synced_at, current_version, shipment_no,
                    local_status, sku, receipt_difference, raw_payload, created_at
                ) values (7, 'PROJECT_CONNECTOR', now(), true, 'KEEP', '已申报', 'PNK-KEEP', 8, '{}', now())
                """);
        var response = objectMapper.readTree("""
                {"code":1,"data":{"total":2,"list":[
                  {"cargoCode":"ONE","cargoStatusName":"已申报","cargoListGoodsDetailResponses":[]}
                ]}}
                """);

        assertThatThrownBy(() -> service.replaceFromConnector(
                "https://czyx.lingxing.com/mp-platform-warehouse-api/api/cargo/list",
                response, LocalDateTime.now()))
                .isInstanceOf(IllegalArgumentException.class)
                .hasMessageContaining("分页未读取完整");
        assertThat(jdbc.queryForObject(
                "select count(*) from wm_ads_shipment_record where current_version=true", Integer.class))
                .isEqualTo(1);
    }

    @Test
    void mapsCurrentLingxingStatusCodesAndExcludesCancelledOrReplacedShipments() throws Exception {
        var response = objectMapper.readTree("""
                {"code":1,"data":{"total":6,"list":[
                  {"cargoCode":"DECLARED","cargoStatusName":"PENDING_SHIPMENT_DETAILS","cargoListGoodsDetailResponses":[{"sku":"PNK-A","diffOfDeclareAndSign":1}]},
                  {"cargoCode":"SHIPPED","cargoStatusName":"AWAITING_DELIVERY","cargoListGoodsDetailResponses":[{"sku":"PNK-B","diffOfDeclareAndSign":2}]},
                  {"cargoCode":"RECEIVING","cargoStatusName":"RECEIVING_IN_PROGRESS","cargoListGoodsDetailResponses":[{"sku":"PNK-C","diffOfDeclareAndSign":3}]},
                  {"cargoCode":"DONE","cargoStatusName":"CLOSED","cargoListGoodsDetailResponses":[{"sku":"PNK-D","diffOfDeclareAndSign":4}]},
                  {"cargoCode":"CANCELLED","cargoStatusName":"CANCELLED","cargoListGoodsDetailResponses":[{"sku":"PNK-E","diffOfDeclareAndSign":5}]},
                  {"cargoCode":"REPLACED","cargoStatusName":"REPLACED","cargoListGoodsDetailResponses":[{"sku":"PNK-F","diffOfDeclareAndSign":6}]}
                ]}}
                """);

        var result = service.replaceFromConnector(
                "https://gw.lingxingerp.com/mp-platform-warehouse-api/api/cargo/list",
                response, LocalDateTime.now());

        assertThat(result.sourceShipments()).isEqualTo(6);
        assertThat(result.importedShipments()).isEqualTo(4);
        assertThat(result.importedRows()).isEqualTo(4);
        assertThat(result.transitUnits()).isEqualByComparingTo("10");
        assertThat(jdbc.queryForList(
                "select local_status from wm_ads_shipment_record order by shipment_no", String.class))
                .containsExactly("已申报", "已完成", "入库中", "已发货");
        assertThat(jdbc.queryForObject(
                "select count(*) from wm_ads_shipment_record where shipment_no in ('CANCELLED','REPLACED')",
                Integer.class)).isZero();
        assertThat(service.status().transitUnits()).isEqualByComparingTo("6");
    }

    @Test
    void rejectsAnyEndpointOutsideTheDocumentedReadOnlyList() throws Exception {
        var response = objectMapper.readTree("""
                {"code":1,"data":{"total":1,"list":[{}]}}
                """);

        assertThatThrownBy(() -> service.replaceFromConnector(
                "https://czyx.lingxing.com/mp-platform-warehouse-api/api/cargo/deleteStorage",
                response, LocalDateTime.now()))
                .isInstanceOf(IllegalArgumentException.class)
                .hasMessageContaining("只接受");
    }
}
