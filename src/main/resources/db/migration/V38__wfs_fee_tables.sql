-- 数据来源：D:\PNK\06WOSZ财务\<月份> 沃尔玛PNK财务数据详情\6.仓储费用明细表、7.WFS配送费报表(2026.04 起更名 7.配送费用明细表)
-- 注意：使用 CREATE TABLE IF NOT EXISTS，允许 Flyway 在已被手工执行过的环境上重复执行而不报错

CREATE TABLE IF NOT EXISTS `wm_ads_wfs_storage_fee` (
  `id`                BIGINT       NOT NULL AUTO_INCREMENT COMMENT '主键，自增',
  `period_start`      DATE         NOT NULL                COMMENT '报表周期起始日（Excel 序列号换算）',
  `period_end`        DATE         NOT NULL                COMMENT '报表周期结束日',
  `period_label`      VARCHAR(16)  NOT NULL                COMMENT '归属月份，如 2026-01（来源文件夹名）',
  `gtin`              VARCHAR(32)  DEFAULT NULL            COMMENT 'GTIN',
  `sku`               VARCHAR(180) DEFAULT NULL            COMMENT '卖家 SKU（完整变体 SKU，如 PNK366069-C-Blue-XL-WFS）',
  `parent_sku`        VARCHAR(80)  DEFAULT NULL            COMMENT '款号（SKU 首段，如 PNK366069）',
  `item_id`           VARCHAR(80)  DEFAULT NULL            COMMENT 'Walmart Item ID',
  `item_name`         VARCHAR(600) DEFAULT NULL            COMMENT '商品名称',
  `length_in`         DECIMAL(10,4) DEFAULT NULL           COMMENT '包装长（inch）',
  `width_in`          DECIMAL(10,4) DEFAULT NULL           COMMENT '包装宽（inch）',
  `height_in`         DECIMAL(10,4) DEFAULT NULL           COMMENT '包装高（inch）',
  `weight_lb`         DECIMAL(12,6) DEFAULT NULL           COMMENT '包装重量（lb）',
  `std_daily_fee`     DECIMAL(14,8) DEFAULT NULL           COMMENT '标准档：日仓储费/件',
  `peak_daily_fee`    DECIMAL(14,8) DEFAULT NULL           COMMENT '旺季档：日仓储费/件',
  `lt_daily_fee`      DECIMAL(14,8) DEFAULT NULL           COMMENT '长期档（366-450 天）：日仓储费/件',
  `lt2_daily_fee`     DECIMAL(14,8) DEFAULT NULL           COMMENT '超长期档（451+ 天）：日仓储费/件（2026-07 起拆分）',
  `std_avg_units`     DECIMAL(16,4) DEFAULT NULL           COMMENT '标准档：平均在库件数',
  `peak_avg_units`    DECIMAL(16,4) DEFAULT NULL           COMMENT '旺季档：平均在库件数',
  `lt_avg_units`      DECIMAL(16,4) DEFAULT NULL           COMMENT '长期档：平均在库件数',
  `lt2_avg_units`     DECIMAL(16,4) DEFAULT NULL           COMMENT '超长期档：平均在库件数',
  `days_in_period`    INT          DEFAULT NULL            COMMENT '周期天数',
  `final_storage_fee` DECIMAL(14,4) NOT NULL DEFAULT 0.0000 COMMENT '本期最终仓储费',
  `original_amount`   DECIMAL(14,4) DEFAULT NULL           COMMENT '原价（2026-06 起的报表才有）',
  `discount_savings`  DECIMAL(14,4) DEFAULT NULL           COMMENT '折扣节省（2026-06 起的报表才有）',
  `source_file`       VARCHAR(300) DEFAULT NULL            COMMENT '来源文件名',
  `imported_at`       DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '导入时间',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_wfs_storage_period_sku` (`period_start`, `sku`),
  KEY `idx_wfs_storage_period` (`period_start`, `period_end`),
  KEY `idx_wfs_storage_parent` (`parent_sku`),
  KEY `idx_wfs_storage_gtin` (`gtin`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='WFS 仓储费明细（SKU 级，来源沃尔玛 storage 报表）';

CREATE TABLE IF NOT EXISTS `wm_ads_wfs_fulfillment_fee` (
  `id`                BIGINT       NOT NULL AUTO_INCREMENT COMMENT '主键，自增',
  `period_start`      DATE         NOT NULL                COMMENT '报表周期起始日（Excel 序列号换算）',
  `period_end`        DATE         NOT NULL                COMMENT '报表周期结束日',
  `period_label`      VARCHAR(16)  NOT NULL                COMMENT '归属月份，如 2026-01（来源文件夹名）',
  `order_id`          VARCHAR(80)  DEFAULT NULL            COMMENT 'Walmart.com Order #',
  `order_line`        VARCHAR(40)  DEFAULT NULL            COMMENT 'Walmart.com Order Line #',
  `po_no`             VARCHAR(80)  DEFAULT NULL            COMMENT 'Walmart.com PO #',
  `po_line`           VARCHAR(40)  DEFAULT NULL            COMMENT 'Walmart.com PO Line #',
  `transaction_type`  VARCHAR(80)  DEFAULT NULL            COMMENT '交易类型：FulfillmentFee / ReturnProcessingFee / LostInventory / RC_InventoryDisposalFee / Refund / Charge 等',
  `reason_code`       VARCHAR(200) DEFAULT NULL            COMMENT '原因码（退货场景为退货原因）',
  `detail`            VARCHAR(200) DEFAULT NULL            COMMENT '计费档位明细，如 Apparel 或 Apparel Under$10',
  `wfs_reference_id`  VARCHAR(300) DEFAULT NULL            COMMENT 'WFSReferenceID，业务唯一键',
  `txn_date`          DATE         DEFAULT NULL            COMMENT '交易日期（Excel 序列号换算）',
  `qty`               DECIMAL(18,4) DEFAULT NULL           COMMENT '数量',
  `billing_method`    VARCHAR(60)  DEFAULT NULL            COMMENT '计费方式（2026-01 报表无此列）',
  `partner_id`        VARCHAR(80)  DEFAULT NULL            COMMENT 'Partner ID',
  `partner_gtin`      VARCHAR(32)  DEFAULT NULL            COMMENT 'Partner GTIN',
  `sku`               VARCHAR(180) DEFAULT NULL            COMMENT '卖家 SKU（由 GTIN 反查补齐，可能为空）',
  `parent_sku`        VARCHAR(80)  DEFAULT NULL            COMMENT '款号（SKU 首段）',
  `partner_item_name` VARCHAR(600) DEFAULT NULL            COMMENT '商品名称',
  `category`          VARCHAR(200) DEFAULT NULL            COMMENT '类目',
  `sub_category`      VARCHAR(200) DEFAULT NULL            COMMENT '子类目',
  `net_payable`       DECIMAL(14,4) DEFAULT NULL           COMMENT '净额（正数=扣费，负数=返还）',
  `original_amount`   DECIMAL(14,4) DEFAULT NULL           COMMENT '原价（2026-06、2026-07 报表才有）',
  `discount_savings`  DECIMAL(14,4) DEFAULT NULL           COMMENT '折扣节省（2026-06、2026-07 报表才有）',
  `customer_order_id` VARCHAR(80)  DEFAULT NULL            COMMENT 'CustomerOrderId',
  `order_channel_id`  VARCHAR(80)  DEFAULT NULL            COMMENT 'OrderChannelId',
  `source_file`       VARCHAR(300) DEFAULT NULL            COMMENT '来源文件名',
  `imported_at`       DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '导入时间',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_wfs_ful_ref` (`wfs_reference_id`),
  KEY `idx_wfs_ful_period` (`period_start`, `period_end`),
  KEY `idx_wfs_ful_type` (`transaction_type`),
  KEY `idx_wfs_ful_parent` (`parent_sku`),
  KEY `idx_wfs_ful_gtin` (`partner_gtin`),
  KEY `idx_wfs_ful_txn_date` (`txn_date`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='WFS 配送/结算费明细（订单行级，来源沃尔玛 settlement 报表，含全部交易类型）';
