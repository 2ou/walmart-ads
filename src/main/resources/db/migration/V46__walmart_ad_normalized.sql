    advertiser_id           BIGINT          NOT NULL,
    ad_type                 VARCHAR(8)      NOT NULL COMMENT 'SP/SB/SV',
    slice_type              VARCHAR(20)     NOT NULL COMMENT 'PAGE_TYPE/PLATFORM',
    entity_key              VARCHAR(255)    NOT NULL,
    source                  VARCHAR(32)     NOT NULL DEFAULT 'LINGXING_MCP',
    attribution_days        INT             NOT NULL DEFAULT 14,
    campaign_id             VARCHAR(64),
    campaign_name           VARCHAR(255),
    campaign_type           VARCHAR(64),
    campaign_status         VARCHAR(64),
    targeting_type          VARCHAR(64),
    ad_group_id             VARCHAR(64),
    ad_group_name           VARCHAR(255),
    dimension_value         VARCHAR(128)    NOT NULL,
    impressions             BIGINT          NOT NULL DEFAULT 0,
    clicks                  BIGINT          NOT NULL DEFAULT 0,
    ad_spend                DECIMAL(18, 6)  NOT NULL DEFAULT 0,
    attributed_sales        DECIMAL(18, 6)  NOT NULL DEFAULT 0,
    attributed_orders       DECIMAL(18, 6)  NOT NULL DEFAULT 0,
    attributed_units        DECIMAL(18, 6)  NOT NULL DEFAULT 0,
    advertised_sku_sales    DECIMAL(18, 6)  NOT NULL DEFAULT 0,
    advertised_sku_units    DECIMAL(18, 6)  NOT NULL DEFAULT 0,
    other_sku_sales         DECIMAL(18, 6)  NOT NULL DEFAULT 0,
    other_sku_units         DECIMAL(18, 6)  NOT NULL DEFAULT 0,
    ntb_orders              DECIMAL(18, 6)  NOT NULL DEFAULT 0,
    ntb_revenue             DECIMAL(18, 6)  NOT NULL DEFAULT 0,
    ntb_units               DECIMAL(18, 6)  NOT NULL DEFAULT 0,
    cpc                     DECIMAL(18, 6)  NOT NULL DEFAULT 0,
    ctr                     DECIMAL(18, 6)  NOT NULL DEFAULT 0,
    cvr                     DECIMAL(18, 6)  NOT NULL DEFAULT 0,
    acos                    DECIMAL(18, 6)  NOT NULL DEFAULT 0,
    roas                    DECIMAL(18, 6)  NOT NULL DEFAULT 0,
    aov                     DECIMAL(18, 6)  NOT NULL DEFAULT 0,
    cpa                     DECIMAL(18, 6)  NOT NULL DEFAULT 0,
    raw_payload             JSON            NOT NULL,
    synced_at               DATETIME        NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_lx_ad_slice (report_date, advertiser_id, ad_type, slice_type, entity_key),
    INDEX idx_lx_ad_slice_date_type (report_date, slice_type, ad_type),
    INDEX idx_lx_ad_slice_campaign (campaign_id, report_date),
    INDEX idx_lx_ad_slice_dimension (slice_type, dimension_value, report_date)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4;

CREATE TABLE wm_ads_lx_ad_sync_log (
    id                      BIGINT          NOT NULL AUTO_INCREMENT,
    started_at              DATETIME        NOT NULL,
    finished_at             DATETIME,
    status                  VARCHAR(20)     NOT NULL COMMENT 'RUNNING/SUCCESS/FAILED',
    source                  VARCHAR(40)     NOT NULL DEFAULT 'lingxing_mcp',
    triggered_by            VARCHAR(20)     NOT NULL COMMENT 'CRON/MANUAL/BACKFILL',
    window_start            DATE            NOT NULL,
    window_end              DATE            NOT NULL,
    attribution_days        INT             NOT NULL DEFAULT 14,
    tool_count              INT             NOT NULL DEFAULT 18,
    completed_tool_count    INT             NOT NULL DEFAULT 0,
    report_rows             INT             NOT NULL DEFAULT 0,
    slice_rows              INT             NOT NULL DEFAULT 0,
    fetched_count           INT             NOT NULL DEFAULT 0,
    error_message           TEXT,
    duration_ms             BIGINT          NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    INDEX idx_lx_ad_log_started (started_at),
    INDEX idx_lx_ad_log_status (status, finished_at)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4;
